def code(rel: str, start: str | None = None, end: str | None = None) -> str:
    """Фрагмент файла: от строки, содержащей start, до строки с end включительно (без докстринга модуля)."""
    text = (ROOT / rel).read_text(encoding="utf-8")
    text = re.sub(r'^""".*?"""\n', "", text, count=1, flags=re.S)
    lines = text.splitlines()
    i = next((k for k, s in enumerate(lines) if start and start in s), 0)
    j = next((k for k, s in enumerate(lines[i:], i) if end and end in s), len(lines) - 1)
    return "\n".join(lines[i:j + 1])


def n(x) -> str:
    return f"{x:,}".replace(",", " ") if isinstance(x, int) else str(x).replace(".", ",")


# ------------------------------------------------------------------ графики
def chart_compactor() -> Path:
    v = R["compactor"]["value"]
    stages = [("до", v["before"]), ("после OPTIMIZE", v["after_optimize"]), ("после VACUUM", v["after_vacuum"])]
    fig, (a1, a2) = plt.subplots(1, 2, figsize=(8, 3.2), dpi=150)
    labels = [s for s, _ in stages]
    a1.bar(labels, [m["table_files"] for _, m in stages], color="#2b7bba", label="в журнале Delta")
    a1.plot(labels, [m["storage_files"] for _, m in stages], "o--", color="#d9534f", label="физически в S3")
    a1.set_title("Число файлов данных", fontsize=10)
    a1.legend(fontsize=8)
    a2.bar(labels, [m["count_s_median"] for _, m in stages], color="#5cb85c")
    a2.set_title("count(), медиана 3 прогонов, с", fontsize=10)
    for ax in (a1, a2):
        ax.tick_params(axis="x", labelsize=8)
    fig.tight_layout()
    path = IMG / "chart_compactor.png"
    fig.savefig(path)
    plt.close(fig)
    return path


