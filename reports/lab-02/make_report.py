"""Собрать отчёт из сохранённых измерений без работающего Docker."""
import json
import statistics
import sys
from pathlib import Path
from textwrap import dedent

from PIL import Image, ImageDraw, ImageFont

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
LAB = ROOT / "labs/lab-02-errors"
sys.path.insert(0, str(HERE.parent / "lib"))
from docx_report import Report  # noqa: E402


def load(name):
    return json.loads((LAB / name).read_text(encoding="utf-8-sig"))


def scheme():
    img = Image.new("RGB", (1050, 440), "white")
    draw = ImageDraw.Draw(img)
    font = ImageFont.truetype("arial.ttf", 22)
    for i, (a, b) in enumerate([
        ("Генератор: N доставок и seed", "Контрольный журнал исходов и часов"),
        ("Redpanda → Spark → Delta raw", "Checkpoint хранит прогресс чтения"),
        ("Разбор и проверка схемы", "Ошибки → DLQ с исходным текстом"),
        ("Фильтр → watermark → дедупликация", "Боты / поздние / повторы → учёт"),
        ("Своевременные визиты → часы", "Поздние → пересчёт и сверка"),
    ]):
        y = i * 86
        for x, label in [(10, a), (520, b)]:
            draw.rounded_rectangle((x, y + 2, x + 510 - 12, y + 60), 8, fill="#e3eef2")
            draw.text((x+10, y+18), label, fill="#15384a", font=font)
        if i < 4:
            draw.text((245, y + 58), "↓", fill="black", font=font)
    path = HERE / "pipeline.png"
    img.save(path)
    return path


def build():
    b, runs = load("results.json"), load("spark-results.json")
    sample = b["series"][-1]["runs"][0]
    n, c = sample["events"], sample["outcomes"]
    r = Report(2, "Обработка ошибок в потоке визитов", HERE / "Отчет_Лаб2_ТКР_Семенов.docx")
    r.h1("Цель и постановка эксперимента")
    r.para("Реализовать семь паттернов обработки ошибок из главы 3 книги Б. Конечны на примере визитов в блоги. "
           "Проверить сохранность данных после сбоя и измерить время приёма при изменении числа доставок.")
    r.para("Объём задаётся точным количеством сообщений N. Повторная доставка и запись с ошибкой входят в N. "
           "Генератор использует фиксированный seed и для каждого сообщения заранее учитывает ожидаемый исход. "
           "Эталонная витрина содержит число уникальных допустимых визитов по часу события.")
    r.figure(scheme(), "Маршрут данных и контроль результата")
    r.h1("Среда и данные")
    r.para("Стенд использует Redpanda, Spark 3.5.8 в режиме local[2], Delta Lake 3.3.3 и SeaweedFS с API S3. "
           "Генератор публикует сообщения в отдельный топик с одной партицией. Offset определяет порядок доставки. "
           "Для каждого повтора создаются новый топик, DLQ, таблицы и checkpoint. "
           "Spark сохраняет сырой поток с trigger(availableNow=True), затем обрабатывает конечную поставку. "
           "Локальная реализация последовательно принимает те же сообщения и позволяет "
           "прервать процесс внутри транзакции.")
    r.para(f"Локальный эксперимент: {b['platform']}, Python {b['python']}, SQLite {b['sqlite']}, "
           f"seed {b['seed']}, {b['batch']} доставок в транзакции. Событие содержит event_id, время ts "
           "в модельных секундах, article_id и признак bot. Нормальная запись продвигает модельное время на две "
           "секунды за шаг. Среди входов есть обрезанный JSON, пропуск article_id, бот, копия последнего нормального "
           "визита и событие на два часа раньше последнего нормального визита.")
    r.h1("Реализация и проверка паттернов")
    r.h2("1. Dead-Letter")
    r.para("Разбор JSON и проверка обязательных полей предшествуют фильтрации. При ошибке сохраняются offset, "
           "исходный текст и причина json либо schema. Spark записывает брак в Delta dlq и Kafka топик с суффиксом "
           "_dlq. Корректные строки того же пакета продолжают обработку. В локальной базе dlq имеет ключ по позиции "
           "записи. Повторная публикация Kafka DLQ при ручном переисполнении пишущего шага может дать дубли.")
    r.h2("2. Filter Interceptor")
    r.para("Правило bot исключает технический трафик из статистики. Счётчик bot сохраняет число исключений. "
           "Каждой доставке назначается один исход в порядке: ошибка JSON, ошибка схемы, бот, опоздание, "
           "дубликат, приём. Баланс всех шести исходов равен N; отфильтрованные визиты можно объяснить по журналу.")
    r.h2("3. Late Data Detector")
    r.para("Порог вычисляется по максимальному времени предыдущих допустимых событий минус 600 секунд. "
           "Запись строго раньше порога уходит на поздний путь. На самой границе запись ещё допустима. "
           "Порог опирается на время события: перезапуск компьютера и текущее время суток его не меняют. "
           "В Spark значение рассчитывается по предшествующим offsets, чтобы будущие "
           "строки не сдвигали порог задним числом.")
    r.h2("4. Windowed Deduplicator")
    r.para("Локальный приёмник держит seen(event_id, ts). При продвижении максимума удаляет ключи старше порога. "
           "Повтор известного ключа в допустимом окне увеличивает duplicate. Слишком старый повтор попадёт на поздний "
           "путь, где при восстановлении часовой статистики используется идентичность события. В Spark сохранённый raw "
           "обрабатывается аналитическими окнами по offsets и event_id. Такой вариант позволяет проверить результат "
           "на конечной поставке, но требует сортировки истории. Экономия памяти "
           "ограниченным состоянием показана в SQLite.")
    r.h2("5. Static Late Data Integrator")
    r.para("Оперативная витрина содержит своевременные уникальные визиты. После поставки пересчитывается заданный "
           "диапазон модельных часов, включая два часа до её начала. В диапазон входят и часы без опозданий. "
           "История для пересчёта включает поздние записи. Горизонт выбран под известную "
           "максимальную задержку генератора.")
    r.h2("6. Dynamic Late Data Integrator")
    r.para("Из поздних событий извлекаются уникальные номера часов. Для этих часов заново считаются визиты по истории, "
           "остальные значения берутся из оперативной витрины. В Spark результат записывается отдельным снимком Delta. "
           "Экономия относится к набору пересчитываемых групп; чтение и запись файлов "
           "зависят от физической организации данных.")
    e = sample["example"]
    if e:
        r.para(f"Пример из поставки {n} сообщений: в модельном часе {e['hour']} первоначально было "
               f"{e['before']} визитов, после интеграции стало {e['after']}. Эталон генератора даёт {e['expected']}. "
               f"Статическая стратегия рассмотрела {sample['static']['hours']} часов, динамическая — "
               f"{sample['dynamic']['hours']}. Обе полные карты часов сверены с эталоном.")
    r.h2("7. Checkpointer")
    rc = b["recovery"]
    r.para("SQLite фиксирует позицию следующего байта, максимум времени, ключи дедупликации, визиты, DLQ и счётчики "
           "одной транзакцией. Дочерний процесс принудительно завершается с кодом 75 внутри обработки очередного "
           "батча. После повторного открытия база откатывает незавершённую транзакцию; чтение начинается с последнего "
           "подтверждённого смещения.")
    r.para(f"В опыте с {rc['events']} сообщениями обработка возобновилась с байта {rc['resume_byte']} и дошла "
           f"до {rc['bytes']}. Хеш упорядоченного содержимого пяти таблиц совпал с непрерывным запуском. "
           "На стенде отдельно воспроизведён штатный рестарт Spark с прежним checkpoint: повтор availableNow сохранил "
           "число строк в raw, количество уникальных offsets равно N.")
    r.h1("Измерение производительности")
    r.para("Время измерено монотонным таймером perf_counter. Локальное измерение "
           "охватывает открытие базы, чтение JSONL, "
           "классификацию и транзакции. Генерация входа, сверка и последующий пересчёт часовых витрин вынесены за этот "
           "интервал. Скорость рассчитана как N / медианное время. Каждый повтор использует новую базу.")
    rows = [["N","JSONL, байт","Повторы","Мин., с","Медиана, с","Макс., с","Сообщ./с"]]
    for s in b["series"]:
        rr = s["runs"]
        ts = [x["seconds"] for x in rr]
        rows.append([rr[0]["events"],rr[0]["bytes"],len(rr),f"{min(ts):.3f}",f"{s['median_s']:.3f}",
                     f"{max(ts):.3f}",round(rr[0]["events"]/s["median_s"])])
    r.table(rows, "Последовательная обработка с транзакционным checkpoint")
    r.para("На стенде интервал приёма включает первое чтение Kafka, запись Delta и контрольный count. "
           "Следующий интервал включает повтор availableNow и проверку offsets. Интервал обработки включает "
           "классификацию, запись DLQ, формирование витрин и чтение исправленных значений. Создание контейнера, "
           "запуск SparkSession, публикация источника и внешняя сверка PowerShell исключены.")
    rows = [["N","Повторы","Приём, с","Рестарт, с","Обработка, с","Обработка мин.–макс., с"]]
    for volume in sorted({x["events"] for x in runs}):
        group = [x for x in runs if x["events"] == volume]
        times = [x["processing_s"] for x in group]
        rows.append([volume,len(group),*[f"{statistics.median(x[k] for x in group):.2f}" for k in
                     ("ingest_s","checkpoint_retry_s","processing_s")], f"{min(times):.2f}–{max(times):.2f}"])
    r.table(rows, "Медианы по фазам Spark на локальном стенде")
    totals = sorted({(x["events"], x["outcomes"].get("json", 0)+x["outcomes"].get("schema", 0)) for x in runs})
    r.para("Число сообщений DLQ по объёмам: " + ", ".join(f"{n} → {bad}" for n, bad in totals) +
           ". Для сохранённой серии разница конечного и начального offset партиции DLQ проверена "
           "через rpk topic describe. Она совпала с суммой ошибок синтаксиса и схемы в каждом прогоне.")
    r.para("На небольших объёмах Spark тратит заметное время на планирование, чтение журнала и коммиты Delta. "
           "Изменение N меняет длину модельной истории. Влияние кэшей ОС и JVM не изолировалось. "
           "Полученные числа характеризуют данные объёмы, конфигурацию и границы таймера.")
    r.table([["Исход","Число доставок"]]+[[k,v] for k,v in c.items()]+[["Всего",sum(c.values())]],
            f"Баланс контрольной поставки из {n} сообщений")
    r.h2("Фрагменты реализации")
    src = (LAB / "bench.py").read_text(encoding="utf-8-sig").splitlines()
    for begin, end, title in [
        ("if ts < maximum - WINDOW:", 'return "ok", max', "Классификация поздней доставки и повтора"),
        ("for key, n in counts.items():", 'db.execute("UPDATE checkpoint', "Счётчики и checkpoint внутри транзакции")
    ]:
        i = next(i for i, line in enumerate(src) if begin in line)
        j = next(j for j in range(i, len(src)) if end in src[j])

        r.listing(dedent("\n".join(src[i:j+1])), title)
    smallest = b["series"][0]
    largest = b["series"][-1]
    ratio = largest["median_s"] / smallest["median_s"]
    r.para(f"При увеличении поставки с {smallest['runs'][0]['events']} до {largest['runs'][0]['events']} "
           f"доставок медианное время локального приёма выросло в {ratio:.1f} раза. Постоянные затраты "
           "на открытие базы и фиксацию небольших транзакций заметнее в коротком прогоне.")
    r.h1("Воспроизведение и вывод")
    r.listing("python labs/lab-02-errors/bench.py --sizes 1000 10000 50000 --repeats 3\n"
              "./labs/lab-02-errors/demo.ps1 -Sizes 1000,10000 -Repeats 3", "Выбор объёма и числа повторов")
    r.para("Для стенда требуются Docker Desktop и образы первой лабораторной. Команды выполняются из корня проекта. "
           "Исходные замеры всех повторов сохранены в results.json и spark-results.json каталога labs/lab-02-errors. "
           "Поле topic идентифицирует отдельный эксперимент в Redpanda Console и в бакете lake/lab02.")
    r.para("Сверка показала, что поздние события меняют уже опубликованные часовые итоги. Обе стратегии восстановили "
           "ожидаемое число визитов в каждом часе. Разделение брака, отфильтрованных записей и повторов сохранило "
           "объяснимый баланс поставки. Совместная фиксация checkpoint и результатов позволила повторить прерванный "
           "батч без расхождений с контрольным прогоном.")
    print(r.save())


if __name__ == "__main__":
    build()
